print('*** Operadores Comparaacion (Relacionales ***)')
a, b= 7, 5
print(f'Valor inicial a: {a}, {b}')

# Operador igual ==
resultado = a == b
print(f'Resultado a == b es: {resultado}')

# Operador diferente !=
resultado= a != b
print(f'Resultado a =! b es: {resultado}')

# Operador menor que
resultado = a > b
print(f'Resultado a > b es: {resultado}')

# Operador mayor que
resultado = a < b
print(f'Resultado a > b es: {resultado}')